"""Export the dev split's prompts for the open-weight run, identical to the Haiku baseline's.

Each line holds the system prompt, the user message (the same format_context output and question
the Haiku baseline received), the offered page ids and the JSON schema with citations restricted
to them. The file contains page text, so it is git-ignored and regenerated by this script.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from maint_copilot.answer import ANSWER_SYSTEM, PROMPT_VERSION, _answer_schema, format_context
from maint_copilot.data import load_benchmark

K = 10
OUT = Path("evals/cluster/inputs_dev_hybrid_k10.jsonl")

# vLLM enforces the schema during decoding, but unlike the Anthropic API it does not tell the
# model what the schema is; one line in the user message does (vLLM docs recommend this).
FORMAT_NOTE = (
    'Reply with JSON only: {"answer": string, "citations": [page ids such as "P123"], '
    '"insufficient_evidence": boolean}.'
)


def main() -> None:
    bench = load_benchmark()
    dev = json.loads(Path("evals/splits/split_v1.json").read_text())["dev"]
    cand = {
        int(k): v
        for k, v in json.loads(
            Path("data/cache/rerank/candidates_dev_hybrid.json").read_text()
        ).items()
    }
    queries = bench.queries.set_index("query_id")
    pages = bench.corpus.set_index("corpus_id")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        for qid in dev:
            ids = cand[int(qid)][:K]
            ctx = [
                {"corpus_id": i, **pages.loc[i, ["doc_id", "page_number_in_doc", "markdown"]]}
                for i in ids
            ]
            user = f"{format_context(ctx)}\n\nQuestion: {queries.loc[qid, 'query']}"
            f.write(
                json.dumps(
                    {
                        "query_id": int(qid),
                        "prompt_version": PROMPT_VERSION,
                        "system": ANSWER_SYSTEM,
                        "user": user + "\n\n" + FORMAT_NOTE,
                        "user_without_format_note_sha256": hashlib.sha256(
                            user.encode()
                        ).hexdigest(),
                        "page_ids": [int(i) for i in ids],
                        "schema": _answer_schema(ids).model_json_schema(),
                    }
                )
                + "\n"
            )
    print(f"wrote {len(dev)} prompts to {OUT} ({OUT.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
